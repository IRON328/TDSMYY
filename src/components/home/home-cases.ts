/** 组别 → 角标配色后缀。本科组用主色，研究生组用次色，便于一眼区分 */
export function catTone(cat: string): '' | 'g' | 'm' | 'o' {
  if (cat === '研究生组') return 'g'
  return ''
}

/** 浏览数千分位，与原型 `fmt()` 一致 */
export function formatViews(n: number): string {
  return String(n).replace(/\B(?=(\d{3})+(?!\d))/g, ',')
}
